// Mensaje para el usuario a partir de cualquier error. Nunca expone texto técnico del servidor.
export function errorMessage(error: unknown): string {
  if (!isAppError(error)) return es.unknownError;
  const base = es.errors[error.code] ?? es.unknownError;
  return error.retryAfterSeconds ? `${base}${es.retryAfter(error.retryAfterSeconds)}` : base;
}
